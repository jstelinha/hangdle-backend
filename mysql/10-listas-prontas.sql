SET NAMES utf8mb4;

-- Listas prontas: modelos que qualquer pessoa copia para as próprias listas (POST /listas-prontas/:id/copias). A
-- cópia vira uma lista comum, que a pessoa edita como quiser; o modelo não muda. As palavras seguem as mesmas
-- regras das palavras das listas (06-listas.sql), para a cópia sempre caber lá.
CREATE TABLE IF NOT EXISTS listas_prontas (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nome VARCHAR(40) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_listas_prontas_nome UNIQUE (nome),
  CONSTRAINT ck_listas_prontas_nome CHECK (CHAR_LENGTH(TRIM(nome)) >= 2)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS palavras_das_listas_prontas (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  lista_pronta_id INT UNSIGNED NOT NULL,
  texto VARCHAR(30) NOT NULL,
  dica VARCHAR(80) NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_palavras_das_listas_prontas_texto UNIQUE (lista_pronta_id, texto),
  CONSTRAINT fk_palavras_das_listas_prontas_lista FOREIGN KEY (lista_pronta_id) REFERENCES listas_prontas (id) ON DELETE CASCADE,
  CONSTRAINT ck_palavras_das_listas_prontas_tamanho CHECK (CHAR_LENGTH(texto) >= 3),
  CONSTRAINT ck_palavras_das_listas_prontas_formato CHECK (
    REGEXP_LIKE(texto, '^[A-ZÁÀÂÃÉÊÍÓÔÕÚÜÇ]+([ -][A-ZÁÀÂÃÉÊÍÓÔÕÚÜÇ]+)*$', 'c')
  ),
  CONSTRAINT ck_palavras_das_listas_prontas_dica CHECK (dica IS NULL OR CHAR_LENGTH(TRIM(dica)) >= 2)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

